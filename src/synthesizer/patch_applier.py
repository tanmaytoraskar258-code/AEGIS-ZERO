import os
import subprocess
import tempfile
from typing import Tuple


class PatchApplier:
    """Safely applies and reverts unified git diff patches on a target repository."""

    def apply_patch(self, repo_path: str, diff_content: str) -> Tuple[bool, str]:
        if not diff_content or "--- " not in diff_content or "+++ " not in diff_content:
            return False, "Invalid unified diff format generated by LLM."

        with tempfile.NamedTemporaryFile(mode="w", suffix=".patch", delete=False, encoding="utf-8") as tmp:
            tmp.write(diff_content)
            patch_file_path = tmp.name

        try:
            # First dry-run check with --check
            check_cmd = ["git", "apply", "--check", "--ignore-space-change", patch_file_path]
            check_res = subprocess.run(check_cmd, cwd=repo_path, capture_output=True, text=True)

            if check_res.returncode != 0:
                return False, f"Patch check failed: {check_res.stderr.strip()}"

            # Apply the patch cleanly
            apply_cmd = ["git", "apply", "--ignore-space-change", patch_file_path]
            apply_res = subprocess.run(apply_cmd, cwd=repo_path, capture_output=True, text=True)

            if apply_res.returncode != 0:
                return False, f"Patch apply failed: {apply_res.stderr.strip()}"

            return True, "Patch applied successfully."
        finally:
            if os.path.exists(patch_file_path):
                os.remove(patch_file_path)

    def revert_changes(self, repo_path: str) -> None:
        """Resets tracked files in the repository back to clean HEAD state."""
        subprocess.run(["git", "checkout", "--", "."], cwd=repo_path, capture_output=True)
